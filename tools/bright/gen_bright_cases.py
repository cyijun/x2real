def case_pos1(task, tier, scene, files):
    if tier == "a":
        return "standard placement (no perturbation; reference for the other cases)"
    g = scene["layout"]["groups"][SPEC[task]["group"]]
    cont = SPEC[task]["container"]
    if task == "pour_beans":
        scene["layout"]["nodes"]["bean_cup"]["placement"]["ranges"] = {"x": [0.02, 0.06], "y": [0.08, 0.12]}
        for sid, s in g["slots"].items():
            s["ranges"]["x"] = [-0.07, -0.03] if sid.startswith("target") else [0.10, 0.14]
        return "cup moved 6 cm back and 10 cm to the right; the bowls moved 10 cm back / 2 cm forward"
    if task == "fold_towel":
        scene["layout"]["nodes"]["towel"]["placement"] = _surf([0.10, 0.12], [-0.10, -0.06], yaws=[0.50, 0.54])
        for sid, s in g["slots"].items():
            s["ranges"]["y"] = [0.33, 0.335] if s["ranges"]["y"][0] > 0 else [-0.335, -0.33]
        _keep_left_cases(g)
        return "towel shifted 6 cm and turned 30 deg; basket pushed to the far side corner"
    if task == "arrange_flowers":
        for sid, s in g["slots"].items():
            if sid.startswith(cont):
                _shift_slot(s, dx=-0.10, dy_inward=0.08)
            else:
                s["yaws"] = [3.10, 3.14]                   # heads toward the robot (rotated 180 deg)
                s["ranges"]["x"] = [-0.12, -0.08]           # origin = stem bottom; the head now reaches x ~ +0.2
        return ("vase moved 10 cm back and 8 cm inward; every rose turned 180 deg (heads toward the robot); "
                "a 30 deg turn of the tightly packed roses is not solvable by the AABB layout solver")
    tool_y = {"p0s0": -0.40, "p0s1": -0.245, "p0s2": -0.09}   # 30 deg turned tools need 15.5 cm spacing
    for sid, s in g["slots"].items():
        if sid.startswith(cont):
            _shift_slot(s, dx=-0.10, dy_inward=0.05, dyaw=(0.52 if task == "handover_tools" else 0.0))
        elif task == "handover_tools":
            y = tool_y[sid.split("_")[0]] * (1 if _slot_side(sid) == "L" else -1)
            s["ranges"] = {"x": [0.10, 0.16], "y": [round(y - 0.003, 4), round(y + 0.003, 4)]}
            s["yaws"] = [0.50, 0.54]
        else:
            _shift_slot(s, dx=-0.08)
    return "container moved 11 cm, items moved 5-8 cm" + (", toolbox and tools turned 30 deg" if task == "handover_tools"
                                                           else "")



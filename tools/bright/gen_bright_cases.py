def build(task, case, tier):
    src = task if case == "train" else SPEC[task]["src"].get(case, task)
    dst = f"{task}_train" if case == "train" else f"{task}_{case}" + ("_b" if tier == "b" else "")
    scene, files = _load_case(src, dst)
    note = make_train(task, scene, files) if case == "train" else EDIT[case](task, tier, scene, files)
    scene["definition"]["metadata"]["semantic_goal"] += f" | case: {note}"
    _write_case(dst, scene, files)
    return dst


def case_names():
    out = []
    for task in SPEC:
        for case in CASES:
            for tier in ("a", "b"):
                out.append((task, case, tier, f"{task}_{case}" + ("_b" if tier == "b" else "")))
        out.append((task, "train", "a", f"{task}_train"))
    out += [("stack_rings", "reorder", "a", "stack_rings_reorder"), ("stack_rings", "reorder", "b", "stack_rings_reorder_b")]
    return out


def extend(defs_module):
    """Called at the end of gen_bright_defs.py: register every case as a task of the same board."""
    global D
    D = defs_module
    for task, case, tier, name in case_names():
        D.TASKS[name] = (lambda t=task, c=case, r=tier: build(t, c, r))
        src = task if case == "train" else SPEC[task]["src"].get(case, task)
        D.TIMEOUTS[name] = D.TIMEOUTS[src]

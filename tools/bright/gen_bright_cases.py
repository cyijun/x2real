def _rename_text(text, src, dst):
    return (text.replace(f"bright/{src}/", f"bright/{dst}/").replace(f"bright_{src}_scene", f"bright_{dst}_scene")
                .replace(f"task_type: bright_{src}", f"task_type: bright_{dst}")
                .replace(f"name: bright_{src}\n", f"name: bright_{dst}\n"))


def _load_case(src, dst):
    D.TASKS[src]()
    scene = yaml.safe_load(_rename_text((D.SCENE_DIR / src / "vnext.yaml").read_text(), src, dst))
    tdir = D.TASK_DIR / src
    files = {p.relative_to(tdir).as_posix(): yaml.safe_load(_rename_text(p.read_text(), src, dst))
             for p in sorted(tdir.rglob("*.yaml"))}
    return scene, files


def _write_case(dst, scene, files):
    sdir, tdir = D.SCENE_DIR / dst, D.TASK_DIR / dst
    for d in (sdir, tdir):
        if d.exists():
            shutil.rmtree(d)
    D.dump(sdir / "vnext.yaml", scene)
    for rel, data in files.items():
        D.dump(tdir / rel, data)


def _events(files):
    """Graph-level event terms (vnext_dag.yaml).  Not the per-stage base: every stage includes it and the
    per-node merge rejects stage-triggered terms ("both define field ... with different content")."""
    comp = files["vnext_dag.yaml"]["graph_task_generator"]["definition"]["component_sections"]
    return comp.setdefault("event_component", {"terms": {}}).setdefault("terms", {})


def _runtime(files):
    return files["vnext_dag.yaml"]["graph_task_generator"]["definition"]["layout"]["runtime_sample"]


def _obj(scene, oid):
    return next(o for o in scene["objects"] if o["id"] == oid)


def _add_object(scene, obj, placement=None):
    scene["objects"].append(obj)
    scene["layout"]["nodes"][obj["id"]] = {"object": obj["id"], **({"placement": placement} if placement else {})}


def _surf(x, y, yaws=None, surface="cloth", orientation=None):
    p = {"type": "surface", "surface": surface, "ranges": {"x": list(x), "y": list(y)}}
    if yaws is not None:
        p["yaws"] = yaws
    if orientation is not None:
        p["orientation"] = orientation
    return p


def _interval(fn, **params):
    return {"_func": f"manaenv.terms.bright_events.{fn}", "mode": "interval", "interval_range_s": [0.1, 0.1],
            "is_global_time": False, **params}


def _set_instruction_note(files, note):
    comp = files["vnext_dag.yaml"]["graph_task_generator"]["definition"]["component_sections"]
    comp.setdefault("log_component", {}).setdefault("entries", {})["bright_case"] = {
        "trigger": "enter", "value": note}


def _keep_left_cases(group):
    """Restrict a mirrored slot group to its authored (l*) cases -- one fixed side for fixture-heavy cases."""
    items = [it for it in group["assignments"]["items"] if it["id"].startswith("l")]
    group["assignments"]["items"] = items
    group["default_assignment"] = items[0]["id"]


def _remove_from_group(group, node):
    group["nodes"] = [n for n in group["nodes"] if n != node]
    for it in group["assignments"]["items"]:
        it["bindings"].pop(node, None)
    for sid in [s for s in group["slots"] if s.startswith(f"{node}_")]:
        group["slots"].pop(sid)


def _slot_side(sid):
    return sid.rsplit("_", 1)[-1]         # "L" or "R"


def _shift_slot(slot, dx=0.0, dy_inward=0.0, dyaw=0.0, side="L"):
    """dy_inward > 0 moves toward the table centre line (y=0 in the cloth frame)."""
    sgn = 1.0 if side == "L" else -1.0      # authored L side is y<0 for items, but containers sit on y>0
    cy = sum(slot["ranges"]["y"]) / 2.0
    toward = -1.0 if cy > 0 else 1.0
    slot["ranges"]["x"] = [round(v + dx, 4) for v in slot["ranges"]["x"]]
    slot["ranges"]["y"] = [round(v + toward * dy_inward, 4) for v in slot["ranges"]["y"]]
    if dyaw:
        slot["yaws"] = [round(v + dyaw, 4) for v in slot["yaws"]]



def case_pos2(task, tier, scene, files):
    g = scene["layout"]["groups"][SPEC[task]["group"]]
    cont = SPEC[task]["container"]
    if tier == "a":
        for sid, s in g["slots"].items():
            if sid.startswith(cont):
                _shift_slot(s, dx=0.03, dy_inward=0.04)
        return "container shifted 3 cm toward the robot and 4 cm inward"
    wedge = SPEC[task]["wedge"]
    x, y, yaw = WEDGE_AT[task]
    big = wedge == "bright_slope_tray"
    L, W = (0.38, 0.32) if big else (0.24, 0.24)
    h0, h1 = 0.012, 0.012 + L * math.tan(math.radians(5.0))
    tray = {"id": "slope_tray", "asset": {"type": "asset_id", "id": wedge}, "semantic_tags": ["fixture"],
            "kinematic": True,
            "anchors": {"local_surfaces": {"top": {
                "center": [0.0, 0.0, round((h0 + h1) / 2, 4)],
                "x_axis": [round(math.cos(math.radians(5)), 5), 0.0, round(math.sin(math.radians(5)), 5)],
                "y_axis": [0.0, 1.0, 0.0],
                "bounds": {"x": [-(L / 2 - 0.01), L / 2 - 0.01], "y": [-(W / 2 - 0.01), W / 2 - 0.01]}}}}}
    _add_object(scene, tray, _surf(x, y, yaws=yaw))
    scene["layout"]["surfaces"]["tray_top"] = {"type": "ref", "ref": "slope_tray.top"}
    _keep_left_cases(g)
    _remove_from_group(g, cont)
    if not g["nodes"]:
        scene["layout"]["groups"].pop(SPEC[task]["group"])
        rs = _runtime(files)
        rs["targets"]["placements"] = [p for p in rs["targets"]["placements"] if p["id"] != SPEC[task]["group"]]
    scene["layout"]["nodes"][cont] = {"object": cont, "placement": _surf([-0.005, 0.005], [-0.005, 0.005], yaws=yaw,
                                                                         surface="tray_top", orientation=TILT_Q)}
    if task == "fold_towel":
        scene["layout"]["nodes"]["towel"]["placement"] = _surf([0.13, 0.16], [-0.06, -0.04], yaws=0.0)
    return f"the {cont} stands on a 5 deg slope tray ({'38 x 32' if big else '24 x 24'} cm, kinematic), fixed side"



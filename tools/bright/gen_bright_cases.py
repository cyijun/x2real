def make_train(task, scene, files):
    """Training distribution: wider continuous ranges / yaws, train-only tablecloths and distractors, wide light."""
    _obj(scene, "tablecloth")["asset"]["candidates"][0]["assets"] = list(TRAIN_CLOTHS)
    g = scene["layout"]["groups"][SPEC[task]["group"]]
    oriented = task in ("handover_tools", "arrange_flowers", "fold_towel")
    for sid, s in g["slots"].items():
        wx = 0.03 if task != "arrange_flowers" else 0.04
        wy = 0.015 if task in ("arrange_flowers", "stack_rings", "handover_tools") else 0.03
        s["ranges"]["x"] = [round(s["ranges"]["x"][0] - wx, 4), round(s["ranges"]["x"][1] + wx, 4)]
        s["ranges"]["y"] = [round(s["ranges"]["y"][0] - wy, 4), round(s["ranges"]["y"][1] + wy, 4)]
        if oriented and task != "arrange_flowers":
            s["yaws"] = [round(s["yaws"][0] - 0.25, 4), round(s["yaws"][1] + 0.25, 4)]
    if task == "fold_towel":
        scene["layout"]["nodes"]["towel"]["placement"]["yaws"] = [-0.35, 0.35]
    for k, pool_assets in enumerate(SPEC[task]["train_distractors"]):
        oid = f"clutter_{k + 1}"
        _add_object(scene, {"id": oid, "asset": {"type": "pool", "candidates": [{"id": "any", "assets": pool_assets}]},
                            "semantic_tags": ["distractor"]}, _surf(*CLUTTER_REGION[task], yaws=[-3.14, 3.14]))
        scene["variants"]["materialization"].append(
            {"id": f"{oid}_pick", "type": "asset_pool_choice",
             "choices": [{"id": "pick_any", "candidate_refs": [f"{oid}.any"], "weight": 1.0}]})
        _runtime(files)["targets"]["assets"].append({"id": f"{oid}_asset", "target": {"type": "node", "id": oid},
                                                     "selector": {"type": "uniform"}})
    dome = _runtime(files)["global"]["lighting"]["dome"]
    dome["intensity"] = {"range": [400.0, 3000.0]}
    dome["color_temperature"] = {"range": [3000.0, 8000.0]}
    return "training distribution"



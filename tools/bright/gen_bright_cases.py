def _correct_prefix(peg):
    """Rings that already sit where they belong: the longest prefix of the peg stack equal to 1, 2, 3, ..."""
    out = []
    for j, k in enumerate(peg):
        if k != j + 1:
            break
        out.append(k)
    return out


def case_reorder(task, tier, scene, files):
    assert task == "stack_rings"
    spec = REORDER[tier]
    g = scene["layout"]["groups"][SPEC[task]["group"]]
    _keep_left_cases(g)
    fixed = ["stacker"] + [f"ring_{k}" for k in spec["peg"]] + [f"ring_{k}" for pair in spec["table_stack"] for k in pair]
    for n in fixed:
        _remove_from_group(g, n)
    # stacker at its authored (left) slot, with one "seat" surface per peg level (all rings on the peg are children
    # of the stacker, so the layout solver treats them as supported, not colliding)
    stacker = _obj(scene, "stacker")
    seats = {f"seat{j}": {"center": [0.0, 0.0, round(D.BASE_H + D.RING_T * j, 4)], "x_axis": [1.0, 0.0, 0.0],
                          "y_axis": [0.0, 1.0, 0.0], "bounds": {"x": [-0.002, 0.002], "y": [-0.002, 0.002]}}
             for j in range(len(spec["peg"]))}
    stacker["anchors"] = {"local_surfaces": seats}
    scene["layout"]["nodes"]["stacker"] = {"object": "stacker", "placement": _surf([0.03, 0.03], [-0.075, -0.075],
                                                                                  yaws=0.0)}
    for j, k in enumerate(spec["peg"]):
        scene["layout"]["surfaces"][f"peg_seat{j}"] = {"type": "ref", "ref": f"stacker.seat{j}"}
        scene["layout"]["nodes"][f"ring_{k}"] = {"object": f"ring_{k}", "placement": _surf(
            [-0.0002, 0.0002], [-0.0002, 0.0002], yaws=0.0, surface=f"peg_seat{j}")}
    for bottom, top in spec["table_stack"]:
        _obj(scene, f"ring_{bottom}")["anchors"] = {"local_surfaces": {"top": {
            "center": [0.0, 0.0, D.RING_T], "x_axis": [1.0, 0.0, 0.0], "y_axis": [0.0, 1.0, 0.0],
            "bounds": {"x": [-0.004, 0.004], "y": [-0.004, 0.004]}}}}
        scene["layout"]["nodes"][f"ring_{bottom}"] = {"object": f"ring_{bottom}",
                                                      "placement": _surf([-0.10, -0.10], [0.21, 0.21], yaws=0.0)}
        scene["layout"]["surfaces"][f"ring{bottom}_top"] = {"type": "ref", "ref": f"ring_{bottom}.top"}
        scene["layout"]["nodes"][f"ring_{top}"] = {"object": f"ring_{top}", "placement": _surf(
            [-0.003, 0.003], [-0.003, 0.003], yaws=0.0, surface=f"ring{bottom}_top")}
    # DAG: press_base -> unstack (top first, every ring above the correct prefix) -> one round per ring that is not
    # already in place -> every ring on the peg in order.  Rings already in place have no round (no free points,
    # no penalty) but must still be there at the end.
    correct = _correct_prefix(spec["peg"])
    unstack = [k for k in reversed(spec["peg"]) if k not in correct]
    dag = files["vnext_dag.yaml"]["graph_task_generator"]
    tname = dag["nodes"][0]["include"].split("/")[3]
    keep = [nd for nd in dag["nodes"] if not any(nd["id"] in (f"pick_ring{k}", f"ring{k}_above_peg", f"ring{k}_aligned",
                                                                f"ring{k}_on_peg") for k in correct)]
    for nd in dag["nodes"]:
        if nd not in keep:
            files.pop(f"stages/{nd['id']}.yaml", None)
    new_nodes = [keep[0]]
    for k in unstack:
        sid = f"unstack_ring{k}"
        files[f"stages/{sid}.yaml"] = D.stage(tname, sid, D.every(
            off_peg=D.negate("around_peg", D.zone(f"@ring_{k}", "@destination", 1, in_reference_frame=True,
                                                  x_range=[-0.012, 0.012], y_range=[-0.012, 0.012],
                                                  z_range=[-0.01, D.PEG_TOP + 0.005])),
            released=D.no_contact([f"ring{k}_left_contact", f"ring{k}_right_contact"], 0.05, 10),
            base_held=D.held_by_any("base", 0.1, 1)), f"misplaced ring {k} taken off the peg and put down")
        new_nodes.append({"id": sid, "include": f"x2real/task/bright/{tname}/stages/{sid}.yaml", "score": 2})
    new_nodes += keep[1:]
    dag["nodes"] = new_nodes
    dag["edges"] = [{"src": a["id"], "dst": b["id"]} for a, b in zip(new_nodes, new_nodes[1:])]
    _add_all_rings_stage(files, n=5)
    comp = files["vnext_dag.yaml"]["graph_task_generator"]["definition"]["component_sections"]
    comp["instruction_component"]["instructions"][0]["text"] = spec["instruction"]
    _events(files)["bright_log_rings"] = _interval("bright_log_poses", asset_cfgs=[f"ring_{k}" for k in range(1, 6)],
                                                   reference="stacker", key="ringlog", at_s=7.0)
    return (f"start: peg (bottom->top) {spec['peg']}, table stacks {spec['table_stack']}; already in place: "
            f"{correct}; unstack first: {unstack}")


